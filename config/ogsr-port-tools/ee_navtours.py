#!/usr/bin/env python3
"""Coverage tours over the AI navigation mesh (level.ai) of every Steam Enhanced Edition level, for the EE test walker (ZoneForge recipe `test-walker`).
  ee_navtours.py [soc|cs|cop ...] [--max-points 1500]      writes <out>/<game>/zf_walker_tours.script  (default out: docs/nav_ee/)
Uses ZoneForge's decoder (navgen.decode_level_ai: level.ai v8 = SoC, v10 = CS / CoP) and its region graph (navgen.bake): the map is cut into square regions, the walker visits
every region of the largest walkable area once in nearest-first order, going through already visited regions when it must. The script holds one line of 'x z y' triples (decimetres)
per level and a get(level) function; the walker then steers between consecutive points with level.vertex_in_direction, so it never leaves the mesh."""
import collections, heapq, sys, time
from pathlib import Path
here = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path.home() / "Documents/GitHub/zoneforge/src"))
from zoneforge import gamefiles, navgen
GAMES = {"soc": "STALKER Shadow of Chornobyl - EE", "cs": "STALKER Clear Sky - EE", "cop": "STALKER Call of Prypiat - EE"}
ROOT = Path("/mnt/games/SteamLibrary/steamapps/common")
def tour(b):
    """indices of regions in visiting order (largest connected area, nearest unvisited first, BFS through the graph)"""
    n = b.count; adj = [list(e) for e in b.edges]
    for i, e in enumerate(b.edges):
        for j in e:
            if i not in adj[j]: adj[j].append(i)                  # one-way links count as walkable both ways for coverage purposes
    seen, best = [False] * n, []
    for s in range(n):
        if seen[s]: continue
        comp, q = [s], collections.deque([s]); seen[s] = True
        while q:
            u = q.popleft()
            for v in adj[u]:
                if not seen[v]: seen[v] = True; comp.append(v); q.append(v)
        if len(comp) > len(best): best = comp
    inside = set(best); start = min(best, key=lambda i: (b.x[i], b.z[i])); visited = {start}; order = [start]; cur = start
    while len(visited) < len(inside):
        prev, q, hit = {cur: None}, collections.deque([cur]), None
        while q and hit is None:
            u = q.popleft()
            for v in adj[u]:
                if v in prev or v not in inside: continue
                prev[v] = u
                if v not in visited: hit = v; break
                q.append(v)
        if hit is None: break
        path = []; u = hit
        while u != cur: path.append(u); u = prev[u]
        for u in reversed(path): order.append(u); visited.add(u)
        cur = hit
    return order
def build(game, maxp):
    van = gamefiles.Vanilla(ROOT / GAMES[game], game); out = {}
    for lv in van.levels():
        t0 = time.time()
        try: m = navgen.decode_level_ai(van.read_level(lv, "level.ai"))
        except Exception as e: print(f"  {game}/{lv}: skipped ({e})"); continue
        k = navgen.region_cells(m.count, m.cell); b = navgen.bake(m, k)
        while b.count > maxp: k = int(k * 1.4) + 1; b = navgen.bake(m, k)
        order = tour(b)
        out[lv] = " ".join(f"{round(b.x[i] * 10)} {round(b.z[i] * 10)} {round(b.y[i] * 10)}" for i in order)
        print(f"  {game}/{lv}: {m.count} nodes -> {b.count} regions (k={k}), tour {len(order)} points, {time.time() - t0:.0f}s")
    return out
def write(game, data, dest):
    p = dest / game; p.mkdir(parents=True, exist_ok=True)
    lines = ["-- zf_walker_tours.script: coverage tours over the AI mesh for the ZoneForge test walker (generated by tools/ee_navtours.py). Do not edit.", "DATA = {"]
    lines += [f'\t["{lv}"] = [[{s}]],' for lv, s in data.items()]
    lines += ["}", "", "-- list of { x, y, z } (metres) for a level, or nil", "function get(level)", "\tlocal s = DATA[level]", "\tif s == nil then return nil end", "\tlocal out, n, v = {}, 0, {}",
              "\tfor num in string.gmatch(s, \"-?%d+\") do", "\t\tv[#v + 1] = tonumber(num) / 10", "\t\tif #v == 3 then n = n + 1 out[n] = { x = v[1], z = v[2], y = v[3] } v = {} end", "\tend", "\treturn out", "end", ""]
    (p / "zf_walker_tours.script").write_text("\n".join(lines)); print(f"wrote {p / 'zf_walker_tours.script'} ({sum(len(s) for s in data.values()) // 1024} KB, {len(data)} levels)")
if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]; maxp = int(sys.argv[sys.argv.index("--max-points") + 1]) if "--max-points" in sys.argv else 1500
    games = [a for a in args if a in GAMES] or list(GAMES)
    for g in games: write(g, build(g, maxp), here / "docs/nav_ee")
