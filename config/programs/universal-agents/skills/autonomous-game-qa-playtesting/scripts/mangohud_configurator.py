def generate_config(preset: str = "telemetry", position: str = "top-right", out_path: Path = None):
    cfg = PRESETS.get(preset, PRESETS["telemetry"]).copy()
    cfg["position"] = position

    lines = [
        "; ========================================================",
        f"; MangoHud Config - Generated by mangohud-configurator ({preset})",
        "; ========================================================"
    ]
    for k, v in cfg.items():
        lines.append(f"{k}={v}")

    content = "\n".join(lines) + "\n"
    if out_path:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(content, encoding="utf-8")
        print(f"[✓] Deployed MangoHud config ({preset}, position={position}) to {out_path}")
    else:
        print(content)
    return 0

def main():
    parser = argparse.ArgumentParser(
        description="MangoHud Performance Telemetry Configurator"
    )
    parser.add_argument("--preset", choices=["telemetry", "compact", "benchmark"], default="telemetry", help="HUD profile")
    parser.add_argument("--position", choices=["top-right", "top-left", "bottom-right", "bottom-left"], default="top-right", help="Screen anchor")
    parser.add_argument("--deploy", action="store_true", help="Write directly to ~/.config/MangoHud/MangoHud.conf")
    parser.add_argument("--out", type=Path, help="Target configuration file path")

    args = parser.parse_args()
    target = None
    if args.deploy:
        target = Path.home() / ".config" / "MangoHud" / "MangoHud.conf"
    elif args.out:
        target = args.out

    return generate_config(preset=args.preset, position=args.position, out_path=target)

if __name__ == "__main__":
    sys.exit(main())
